/**
 * S3 key rules for the Video Text tool. Pure — no AWS, safe on the client.
 *
 * Everything lives under the private mastering workspace (kept off the public
 * CDN by the bucket-policy Deny), one folder per project, so a project's files
 * can be recognised and expired together.
 */

export const VIDEO_TEXT_PREFIX = 'audio/mastering/video-text/';

/** 1 GiB cap on an uploaded source video. */
export const MAX_VIDEO_TEXT_BYTES = 1024 * 1024 * 1024;

/** Files are deleted this many days after they are written (S3 lifecycle rule). */
export const RETENTION_DAYS = 30;

/** Project ids are generated by crypto.randomUUID(); accept only key-safe characters. */
export function isValidProjectId(id: string): boolean {
  return typeof id === 'string' && /^[A-Za-z0-9_-]{1,64}$/.test(id);
}

function projectPrefix(projectId: string): string {
  if (!isValidProjectId(projectId)) throw new Error('invalid video text project id');
  return `${VIDEO_TEXT_PREFIX}${projectId}/`;
}

/** Ids from the render pipeline (render, block) must also be key-safe. */
function safeToken(value: string, what: string): string {
  if (!isValidProjectId(value)) throw new Error(`invalid ${what}`);
  return value;
}

function sourceExtensionFor(contentType: string): string {
  return String(contentType).toLowerCase() === 'video/quicktime' ? '.mov' : '.mp4';
}

/**
 * A collision-proof key for an uploaded source video. The filename is kept
 * (sanitised, as masteringCoverKey does) behind a timestamp+nonce, so a
 * re-upload never clobbers an earlier one. `now`/`nonce` are injected to stay pure.
 */
export function sourceKey(
  projectId: string,
  filename: string,
  contentType: string,
  now: number,
  nonce: string,
): string {
  const safe =
    String(filename ?? '')
      .replace(/\.[a-z0-9]+$/i, '')
      .replace(/[^a-zA-Z0-9-]/g, '_')
      .replace(/_{2,}/g, '_')
      .replace(/^_|_$/g, '')
      .slice(0, 80) || 'source';
  const safeNonce = String(nonce).replace(/[^a-zA-Z0-9-]/g, '').slice(0, 32) || 'x';
  return `${projectPrefix(projectId)}source/${now}_${safeNonce}_${safe}${sourceExtensionFor(contentType)}`;
}

/** Everything one render writes sits under this prefix. */
export function renderPrefix(projectId: string, renderId: string): string {
  return `${projectPrefix(projectId)}render-${safeToken(renderId, 'render id')}/`;
}

export function overlayKey(projectId: string, renderId: string, blockId: string): string {
  return `${renderPrefix(projectId, renderId)}overlay-${safeToken(blockId, 'block id')}.png`;
}

function pad(index: number): string {
  return String(Math.max(0, Math.floor(index))).padStart(4, '0');
}

export function segmentKey(projectId: string, renderId: string, index: number): string {
  return `${renderPrefix(projectId, renderId)}segment-${pad(index)}.mp4`;
}

export function chunkOutKey(projectId: string, renderId: string, index: number): string {
  return `${renderPrefix(projectId, renderId)}chunk-${pad(index)}.mp4`;
}

export function outputKey(projectId: string, renderId: string): string {
  return `${renderPrefix(projectId, renderId)}output.mp4`;
}

/** True if the key is a file inside this project's own folder. */
export function isVideoTextKeyFor(projectId: string, key: string): boolean {
  if (!isValidProjectId(projectId) || typeof key !== 'string') return false;
  const prefix = `${VIDEO_TEXT_PREFIX}${projectId}/`;
  return key.startsWith(prefix) && key.length > prefix.length && key.length <= 1024 && !key.includes('..');
}

/** The deletion date for a file written at `writtenAtIso`: RETENTION_DAYS later. */
export function expiresAtFrom(writtenAtIso: string): string {
  const d = new Date(writtenAtIso);
  if (Number.isNaN(d.getTime())) throw new Error('invalid timestamp');
  d.setUTCDate(d.getUTCDate() + RETENTION_DAYS);
  return d.toISOString();
}
